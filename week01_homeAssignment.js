 // Grade Classification using if...else if...else
 let mark = 70

if (mark < 0 || mark > 100) {
console.log("Invalid mark");
} 
else if (mark >= 90) {
console.log("Grade A");
} 
else if (mark >= 80) {
console.log("Grade B");
} 
else if (mark >= 70) {
console.log("Grade C");
} 
else if (mark >= 60) {
console.log("Grade D");
} 
else if (mark >= 50) {
console.log("Grade E");
}
 else {
console.log("Grade F (Fail)");
}   